class TestGenerateDailyNote:
    """Test generate_daily_note method."""

    def test_generate_empty_note(self, notebook):
        note = notebook.generate_daily_note(date="2026-07-02")
        assert note.date == "2026-07-02"
        assert "Limited data" in note.content or note.content

    def test_generate_note_with_regime(self, notebook):
        note = notebook.generate_daily_note(
            date="2026-07-02",
            regime_data={"regime": "bullish", "confidence": 0.80},
        )
        assert note.market_regime == "bullish"
        assert note.regime_confidence == 0.80
        assert "bullish" in note.content

    def test_generate_note_with_performance(self, notebook):
        note = notebook.generate_daily_note(
            date="2026-07-02",
            performance_data={
                "total_trades": 10,
                "total_pl": 500.0,
                "win_rate": 80.0,
                "profit_factor": 2.5,
                "average_winner": 100.0,
                "average_loser": -50.0,
            },
        )
        assert note.trade_count == 10
        assert note.daily_pl == 500.0
        assert note.win_rate == 80.0
        assert "Strong day" in note.content  # win_rate >= 70
        assert "Profit factor: 2.5" in str(note.trade_observations)

    def test_generate_note_average_day(self, notebook):
        note = notebook.generate_daily_note(
            date="2026-07-02",
            performance_data={
                "total_trades": 5,
                "total_pl": 50.0,
                "win_rate": 60.0,
            },
        )
        assert "Average day" in note.content

    def test_generate_note_below_average_day(self, notebook):
        note = notebook.generate_daily_note(
            date="2026-07-02",
            performance_data={
                "total_trades": 5,
                "total_pl": -100.0,
                "win_rate": 20.0,
            },
        )
        assert "Below-average" in note.content

    def test_generate_note_with_rs_data(self, notebook):
        note = notebook.generate_daily_note(
            date="2026-07-02",
            rs_data={
                "all_symbols": [
                    {"symbol": "AAPL", "rs_score": 90.0},
                    {"symbol": "NVDA", "rs_score": 85.0},
                    {"symbol": "TSLA", "rs_score": 30.0},
                ],
            },
        )
        assert any("AAPL" in l for l in note.rs_leaders)
        assert any("TSLA" in l for l in note.rs_laggards)

    def test_generate_note_with_trades(self, notebook):
        trades = [
            {"exit_price": 110.0, "exit_reason": "target", "holding_period_seconds": 3600},
            {"exit_price": 105.0, "exit_reason": "target", "holding_period_seconds": 7200},
        ]
        note = notebook.generate_daily_note(
            date="2026-07-02",
            trades=trades,
        )
        assert any("target" in obs for obs in note.trade_observations)
        assert any("hours" in obs for obs in note.trade_observations)

    def test_generate_note_auto_date(self, notebook):
        note = notebook.generate_daily_note()
        from datetime import datetime
        today = datetime.utcnow().strftime("%Y-%m-%d")
        assert note.date == today


class TestSaveAndLoadNotes:
    """Test saving and loading notes."""

    def test_save_note_creates_json(self, notebook):
        note = ResearchNote(
            date="2026-07-02",
            content="Test",
            market_regime="bullish",
        )
        path = notebook.save_note(note)
        assert path.exists()
        assert path.suffix == ".json"

    def test_save_note_creates_markdown(self, notebook):
        note = ResearchNote(
            date="2026-07-02",
            content="Test",
        )
        notebook.save_note(note)
        md_path = notebook.md_dir / "2026-07-02.md"
        assert md_path.exists()
        assert "Research Note" in md_path.read_text()

    def test_save_note_json_content(self, notebook):
        note = ResearchNote(
            date="2026-07-02",
            content="Market up",
            market_regime="bullish",
            hypotheses=["H1"],
            trade_count=10,
        )
        notebook.save_note(note)
        data = json.loads((notebook.notes_dir / "2026-07-02.json").read_text())
        assert data["date"] == "2026-07-02"
        assert data["content"] == "Market up"
        assert data["market_regime"] == "bullish"
        assert data["hypotheses"] == ["H1"]
        assert data["trade_count"] == 10

    def test_get_recent_notes_empty(self, notebook):
        notes = notebook.get_recent_notes()
        assert notes == []

    def test_get_recent_notes(self, notebook):
        for day in range(1, 6):
            note = ResearchNote(
                date=f"2026-07-{day:02d}",
                content=f"Day {day}",
            )
            notebook.save_note(note)

        notes = notebook.get_recent_notes()
        assert len(notes) >= 5

    def test_get_recent_notes_limit(self, notebook):
        for day in range(1, 11):
            note = ResearchNote(
                date=f"2026-07-{day:02d}",
                content=f"Day {day}",
            )
            notebook.save_note(note)

        notes = notebook.get_recent_notes(limit=3)
        assert len(notes) == 3


