# ---- ResearchNote dataclass tests ----

class TestResearchNoteDataclass:
    """Test ResearchNote dataclass."""

    def test_defaults(self):
        note = ResearchNote()
        assert note.date == ""
        assert note.trade_count == 0
        assert note.daily_pl == 0.0
        assert note.hypotheses == []

    def test_to_dict(self):
        note = ResearchNote(
            date="2026-07-02",
            content="Test content",
            market_regime="bullish",
            regime_confidence=0.75,
            rs_leaders=["AAPL (score: 80)"],
            trade_count=5,
            daily_pl=150.0,
            win_rate=80.0,
        )
        d = note.to_dict()
        assert d["date"] == "2026-07-02"
        assert d["market_regime"] == "bullish"
        assert d["regime_confidence"] == 0.75
        assert d["trade_count"] == 5
        assert d["daily_pl"] == 150.0
        assert isinstance(d["rs_leaders"], list)

    def test_to_dict_roundtrip(self):
        note = ResearchNote(
            date="2026-07-02",
            content="Test",
            market_regime="volatile",
            hypotheses=["H1"],
            data_needed=["More data"],
        )
        d = note.to_dict()
        note2 = ResearchNote(**d)
        assert note2.date == note.date
        assert note2.market_regime == note.market_regime
        assert note2.hypotheses == note.hypotheses

    def test_to_markdown_basic(self):
        note = ResearchNote(
            date="2026-07-02",
            content="Market was choppy today.",
            market_regime="volatile",
            regime_confidence=0.60,
        )
        md = note.to_markdown()
        assert "# Research Note" in md
        assert "2026-07-02" in md
        assert "volatile" in md
        assert "Market was choppy today" in md

    def test_to_markdown_with_trades(self):
        note = ResearchNote(
            date="2026-07-02",
            daily_pl=250.00,
            trade_count=10,
            win_rate=70.0,
        )
        md = note.to_markdown()
        assert "$250.00" in md
        assert "**Trade Count:**" in md
        assert "**Win Rate:**" in md

    def test_to_markdown_with_leaders(self):
        note = ResearchNote(
            date="2026-07-02",
            rs_leaders=["AAPL (score: 80)", "NVDA (score: 75)"],
        )
        md = note.to_markdown()
        assert "Relative Strength Leaders" in md
        assert "AAPL" in md
        assert "NVDA" in md

    def test_to_markdown_with_laggards(self):
        note = ResearchNote(
            date="2026-07-02",
            rs_laggards=["TSLA (score: 20)"],
        )
        md = note.to_markdown()
        assert "Relative Strength Laggards" in md
        assert "TSLA" in md

    def test_to_markdown_with_hypotheses(self):
        note = ResearchNote(
            date="2026-07-02",
            hypotheses=["H1: RS stocks win more"],
        )
        md = note.to_markdown()
        assert "Hypotheses" in md
        assert "H1" in md
        assert "testable hypotheses" in md.lower() or "hypotheses" in md.lower()

    def test_to_markdown_with_patterns(self):
        note = ResearchNote(
            date="2026-07-02",
            patterns=["Pattern A observed"],
        )
        md = note.to_markdown()
        assert "Emerging Patterns" in md

    def test_to_markdown_with_confidence(self):
        note = ResearchNote(
            date="2026-07-02",
            confidence="Low",
        )
        md = note.to_markdown()
        assert "Confidence Level" in md
        assert "Low" in md

    def test_to_markdown_with_data_needed(self):
        note = ResearchNote(
            date="2026-07-02",
            data_needed=["Sector data"],
        )
        md = note.to_markdown()
        assert "Additional Data Needed" in md

    def test_to_markdown_footer(self):
        note = ResearchNote(date="2026-07-02")
        md = note.to_markdown()
